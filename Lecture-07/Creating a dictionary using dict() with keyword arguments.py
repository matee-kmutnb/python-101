# Creating a dictionary using dict() with keyword arguments
student = dict(name="Alice", age=25, grade="A")
print(student) # Output: {'name': 'Alice', 'age': 25, 'grade': 'A'}

# Creating a dictionary using dict() with a list of tuples
student = dict([("name", "Alice"), ("age", 25), ("grade", "A")])
print(student) # Output: {'name': 'Alice', 'age': 25, 'grade': 'A'}